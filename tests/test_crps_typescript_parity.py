"""The optional browser preview must reproduce Python's seven-factor arithmetic.

Fixtures are generated by the authoritative Python implementation, not copied
from the TypeScript port. Node only transcompiles the existing TypeScript file.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

from bmw_pm.contracts import CriterionInput
from bmw_pm.decision.crps import FACTOR_ORDER, compute_crps, compute_decision_confidence, compute_evidence_strength

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "web"
NODE_SCRIPT = r"""
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const ts = require(path.join(process.cwd(), 'node_modules/typescript'));
const filename = path.join(process.cwd(), 'lib/domain/crps.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const mod = new Module(filename, module);
mod.filename = filename;
mod.paths = Module._nodeModulePaths(path.dirname(filename));
mod._compile(compiled, filename);
let text = '';
process.stdin.on('data', chunk => text += chunk);
process.stdin.on('end', () => {
  const fixtures = JSON.parse(text);
  process.stdout.write(JSON.stringify(fixtures.map(fixture => ({
    result: mod.exports.previewCrps(fixture.factors),
    confidence: mod.exports.previewDecisionConfidence(fixture.strength)
  }))));
});
"""


def test_python_typescript_crps_and_confidence_parity():
    if not shutil.which("node") or not (WEB / "node_modules/typescript").exists():
        pytest.skip("Node/TypeScript workspace dependencies are unavailable")
    known = {name: CriterionInput(value=2.0, basis=f"reviewed {name}") for name in FACTOR_ORDER}
    fixtures = [
        known,
        {**known, "frequency": CriterionInput(missing_reason="No population denominator")},
        {**known, "competitive_gap": CriterionInput(lower_value=1.0, upper_value=3.0, basis="matched dimensions")},
        {name: CriterionInput(missing_reason=f"Missing {name}") for name in FACTOR_ORDER},
        {**known, "customer_impact": CriterionInput(value=4.0, basis="PM input"),
         "evidence_strength": CriterionInput(value=3.0, basis="source review")},
    ]
    strength = compute_evidence_strength([
        {"evidence_id": "EXT-A", "source_quality": 83, "independence_group": "A",
         "source_family": "independent_test_org", "published_at": "2026-01-01"},
        {"evidence_id": "EXT-B", "source_quality": 71, "independence_group": "B",
         "source_family": "professional_review", "published_at": "2025-01-01"},
    ])
    oracle_confidence = compute_decision_confidence(strength)
    inputs = [{"factors": {key: value.model_dump(mode="json") for key, value in factor_set.items()},
               "strength": {"value": strength.value, "components": strength.components}}
              for factor_set in fixtures]
    process = subprocess.run(["node", "-e", NODE_SCRIPT], input=json.dumps(inputs),
                             cwd=WEB, text=True, capture_output=True, check=True)
    actual = json.loads(process.stdout)
    for factors, item in zip(fixtures, actual, strict=True):
        expected = compute_crps(factors)
        result = item["result"]
        assert result["crps_100_lower"] == pytest.approx(expected.crps_100_lower)
        assert result["crps_100_upper"] == pytest.approx(expected.crps_100_upper)
        assert result["band"] == expected.band
        assert result["unknown_factors"] == expected.unknown_factors
        for name in FACTOR_ORDER:
            assert result["factors"][name]["lower_contribution"] == pytest.approx(
                expected.factors[name].lower_contribution)
            assert result["factors"][name]["upper_contribution"] == pytest.approx(
                expected.factors[name].upper_contribution)
        assert item["confidence"]["value_0_to_100"] == pytest.approx(oracle_confidence.value_0_to_100)
