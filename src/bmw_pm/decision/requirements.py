"""Deterministically consolidate validated signals into source-linked customer requirements."""

from __future__ import annotations

from collections import defaultdict
from typing import Any, Sequence

from ..contracts import (
    AcceptanceProposal,
    FeedbackRecord,
    Polarity,
    RequirementRevision,
    RequirementEvidenceLink,
    RequirementScope,
    Signal,
)
from ..utils import stable_id, utc_now


def build_requirement_candidates(
    *,
    signals: Sequence[Signal],
    eligible_records: Sequence[FeedbackRecord],
    processed_record_ids: set[str],
    profile: dict[str, Any],
    created_by: str,
) -> list[RequirementRevision]:
    grouped: dict[tuple[str, str], list[Signal]] = defaultdict(list)
    for signal in signals:
        grouped[(signal.need_domain, signal.customer_outcome.strip())].append(signal)
    candidates: list[RequirementRevision] = []
    eligible_by_id = {record.record_id: record for record in eligible_records}
    for (domain, outcome), domain_signals in sorted(grouped.items()):
        configured_powertrains = profile.get("domain_applicability", {}).get(domain)
        scope_powertrains = list(configured_powertrains or profile.get("powertrains", []))
        scoped_records = [
            record for record in eligible_records
            if not scope_powertrains or record.powertrain in scope_powertrains
        ]
        scoped_ids = {record.record_id for record in scoped_records}
        domain_signals = [
            signal for signal in domain_signals if signal.feedback_record_id in scoped_ids
        ]
        support_signals = [
            item
            for item in domain_signals
            if item.polarity in {Polarity.COMPLAINT, Polarity.ASPIRATION}
        ]
        counter_signals = [item for item in domain_signals if item.polarity == Polarity.PRAISE]
        context_signals = [
            item for item in domain_signals
            if item.polarity in {Polarity.MIXED, Polarity.OBSERVATION}
        ]
        # Count source records once even when extraction yields several signals per record.
        support_records = {item.feedback_record_id for item in support_signals}
        counter_records = {item.feedback_record_id for item in counter_signals} - support_records
        if not support_records:
            continue
        if not support_records <= set(eligible_by_id):
            raise ValueError("supporting signal references an ineligible feedback record")
        requirement_id = stable_id(
            "req", str(profile["profile_id"]), domain, outcome.casefold()
        )
        provider_modes = sorted({item.provider_mode for item in domain_signals})
        assumptions = [
            "Feedback IDs are records, not verified unique people or customers.",
            "Collected-corpus mention share is descriptive and is not population prevalence.",
            "Source A-D identities and verified owner/expert status are unavailable.",
        ]
        if "baseline_no_ai" in provider_modes:
            assumptions.append(
                "Signals were generated by the deterministic keyword baseline, not AI; extraction quality has not been measured."
            )
        links: list[RequirementEvidenceLink] = []
        for role, group in (
            ("supports", support_signals),
            ("preserves", counter_signals),
            ("context", context_signals),
        ):
            for signal in group:
                record = eligible_by_id[signal.feedback_record_id]
                if not signal.evidence_spans:
                    raise ValueError(f"signal {signal.signal_id} has no evidence span")
                for span in signal.evidence_spans:
                    if (
                        span.record_id != record.record_id
                        or record.redacted_text[span.start:span.end] != span.text
                        or span.locator.source_id != record.source_id
                        or span.locator.source_hash != record.row_locators[0].source_hash
                        or span.locator.exact_quote != span.text
                    ):
                        raise ValueError(f"signal {signal.signal_id} has unresolved evidence")
                    links.append(
                        RequirementEvidenceLink(
                            signal_id=signal.signal_id,
                            role=role,
                            atomic_claim=signal.atomic_claim,
                            locator=span.locator,
                            exact_span_checked=True,
                        )
                    )
        candidates.append(
            RequirementRevision(
                requirement_id=requirement_id,
                revision=1,
                title=domain.replace("_", " ").title(),
                customer_outcome=outcome,
                scope=RequirementScope(
                    models=[str(profile["model_family"])],
                    countries=list(profile.get("countries", [])),
                    powertrains=scope_powertrains,
                ),
                use_conditions=[
                    "Conditions are limited to those stated in linked feedback; a reviewed test protocol is pending."
                ],
                acceptance_proposal=AcceptanceProposal(
                    method="Comparative customer task/experience study; protocol and target pending PM and engineering review."
                ),
                target_status="pending_engineering_review",
                supporting_signal_ids=sorted({item.signal_id for item in support_signals}),
                counter_signal_ids=sorted({item.signal_id for item in counter_signals}),
                context_signal_ids=sorted({item.signal_id for item in context_signals}),
                evidence_links=links,
                alternatives=[
                    "Investigate solution alternatives only after validating the customer task and constraints."
                ],
                assumptions=assumptions,
                missing_evidence=[
                    "Engineering feasibility and implementation cost are not supplied.",
                    "Feedback observation dates and sampling frame are not supplied.",
                    "Customer-study respondent counts and scale endpoints are not supplied.",
                    "A reviewed crosswalk from this need to customer-study categories is not yet available.",
                    "No China verbatims are supplied; zero signals cannot establish no need there.",
                    "Strategic and competitive/outlook criteria require PM-approved objectives and matched evidence.",
                    "Exact text spans were checked automatically; semantic entailment still needs human adjudication.",
                ],
                feasibility="unknown",
                lifecycle_status="needs_review",
                created_by=created_by,
                created_at=utc_now(),
                denominator_feedback_records=len(scoped_ids),
                processed_feedback_records=len(processed_record_ids & scoped_ids),
                support_count=len(support_records),
                counter_count=len(counter_records),
            )
        )
    return candidates
