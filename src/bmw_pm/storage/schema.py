"""Administrator-owned PostgreSQL schema and narrowly scoped team roles."""
from __future__ import annotations

import re

from .config import StorageError
from .database import SCHEMA
from .postgres import SCHEMA_VERSION, WRITE_LOCK

BASE_TABLES = re.findall(r'CREATE TABLE IF NOT EXISTS (\w+)', SCHEMA)
EXTRA_SCHEMA = '''
CREATE TABLE IF NOT EXISTS imported_evidence (
 archive_sha256 TEXT NOT NULL, table_name TEXT NOT NULL, row_key TEXT NOT NULL,
 payload_json TEXT NOT NULL, payload_hash TEXT NOT NULL,
 PRIMARY KEY (archive_sha256,table_name,row_key));
CREATE UNIQUE INDEX IF NOT EXISTS ix_imported_row_key ON imported_evidence(row_key);
CREATE TABLE IF NOT EXISTS bmw_context (
 observation_id TEXT PRIMARY KEY, source_id TEXT NOT NULL REFERENCES sources(source_id),
 payload_json TEXT NOT NULL, payload_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS source_acquisitions (
 acquisition_id TEXT PRIMARY KEY, source_id TEXT NOT NULL REFERENCES sources(source_id),
 payload_json TEXT NOT NULL, payload_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS youtube_bundles (bundle_hash TEXT PRIMARY KEY, payload_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS youtube_findings (evidence_id TEXT PRIMARY KEY, payload_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS video_memories (
 memory_id TEXT PRIMARY KEY, video_id TEXT NOT NULL, model_code TEXT NOT NULL,
 market TEXT, created_at TEXT NOT NULL, payload_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS successor_drafts (
 draft_id TEXT PRIMARY KEY, payload_json TEXT NOT NULL, payload_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS shared_source_files (
 relative_path TEXT NOT NULL, sha256 TEXT NOT NULL, byte_count BIGINT NOT NULL,
 content BYTEA NOT NULL, PRIMARY KEY(relative_path,sha256));
CREATE TABLE IF NOT EXISTS migration_runs (
 fingerprint TEXT PRIMARY KEY, created_at TEXT NOT NULL, manifest_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS schema_version (
 singleton INTEGER PRIMARY KEY CHECK(singleton=1), version TEXT NOT NULL);
'''
APPLICATION_TABLES = BASE_TABLES + re.findall(r'CREATE TABLE IF NOT EXISTS (\w+)', EXTRA_SCHEMA)
MIGRATABLE_TABLES = [t for t in APPLICATION_TABLES if t not in {'shared_source_files', 'migration_runs', 'schema_version'}]
ROW_ORDER_TABLES = {'score_snapshots', 'decisions', 'priority_assessments', 'evidence_link_judgments'}
IMMUTABLE_TABLES = ['audit_events', 'requirement_revisions', 'evidence_link_judgments',
                    'priority_assessments', 'successor_drafts', 'video_memories', 'shared_source_files', 'migration_runs']


def postgres_schema() -> str:
    ddl = re.sub(r'CREATE TRIGGER IF NOT EXISTS.*?END;', '', SCHEMA, flags=re.S)
    ddl = ddl.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT PRIMARY KEY')
    ddl = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', ddl)
    return ddl + EXTRA_SCHEMA


def install_schema(connection) -> None:
    """Create only bmw_pm objects, with no grants to public API roles."""
    from psycopg import sql
    connection.write_lock()
    raw = connection.raw
    raw.execute('CREATE SCHEMA IF NOT EXISTS bmw_pm')
    raw.execute('REVOKE ALL ON SCHEMA bmw_pm FROM PUBLIC')
    raw.execute(postgres_schema())
    for table in ROW_ORDER_TABLES:
        raw.execute(sql.SQL('ALTER TABLE {} ADD COLUMN IF NOT EXISTS _insertion_order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE')
                    .format(sql.Identifier(table)))
    current = raw.execute('SELECT version FROM schema_version WHERE singleton=1').fetchone()
    if current and current[0] != SCHEMA_VERSION:
        raise StorageError('The target schema has a different version. No migration was performed.')
    raw.execute('INSERT INTO schema_version VALUES (1,%s) ON CONFLICT DO NOTHING', (SCHEMA_VERSION,))
    raw.execute('''CREATE OR REPLACE FUNCTION bmw_pm.reject_mutation() RETURNS trigger
        LANGUAGE plpgsql SET search_path = bmw_pm, pg_catalog AS $$
        BEGIN RAISE EXCEPTION 'immutable append-only application record' USING ERRCODE='23514'; END; $$''')
    for table in IMMUTABLE_TABLES:
        trigger = table + '_immutable'
        exists = raw.execute('SELECT 1 FROM pg_trigger WHERE tgname=%s AND tgrelid=%s::regclass',
                             (trigger, 'bmw_pm.' + table)).fetchone()
        if not exists:
            raw.execute(sql.SQL('CREATE TRIGGER {} BEFORE UPDATE OR DELETE ON {} FOR EACH ROW EXECUTE FUNCTION bmw_pm.reject_mutation()')
                        .format(sql.Identifier(trigger), sql.Identifier(table)))
    for role in ('bmw_pm_reader', 'bmw_pm_writer'):
        existing = raw.execute('SELECT rolcanlogin,rolsuper,rolbypassrls FROM pg_roles WHERE rolname=%s', (role,)).fetchone()
        if existing and any(existing):
            raise StorageError('A team group role already exists with unexpected privileges.')
        if not existing:
            raw.execute(sql.SQL('CREATE ROLE {} NOLOGIN NOSUPERUSER NOBYPASSRLS').format(sql.Identifier(role)))
        raw.execute(sql.SQL('GRANT USAGE ON SCHEMA bmw_pm TO {}').format(sql.Identifier(role)))
        raw.execute(sql.SQL('GRANT SELECT ON ALL TABLES IN SCHEMA bmw_pm TO {}').format(sql.Identifier(role)))
    for table in APPLICATION_TABLES:
        raw.execute(sql.SQL('REVOKE ALL ON {} FROM PUBLIC').format(sql.Identifier(table)))
        # Explicit role policies keep these tables closed even if someone later exposes the schema.
        raw.execute(sql.SQL('ALTER TABLE {} ENABLE ROW LEVEL SECURITY').format(sql.Identifier(table)))
        policies = {row[0] for row in raw.execute('SELECT policyname FROM pg_policies WHERE schemaname=%s AND tablename=%s', ('bmw_pm', table))}
        if 'team_read' not in policies:
            raw.execute(sql.SQL('CREATE POLICY team_read ON {} FOR SELECT TO bmw_pm_reader,bmw_pm_writer USING (true)').format(sql.Identifier(table)))
        if table not in {'schema_version', 'migration_runs'}:
            raw.execute(sql.SQL('GRANT INSERT ON {} TO bmw_pm_writer').format(sql.Identifier(table)))
            if 'team_insert' not in policies:
                raw.execute(sql.SQL('CREATE POLICY team_insert ON {} FOR INSERT TO bmw_pm_writer WITH CHECK (true)').format(sql.Identifier(table)))
    for role in ('anon', 'authenticated', 'service_role'):
        if raw.execute('SELECT 1 FROM pg_roles WHERE rolname=%s', (role,)).fetchone():
            raw.execute(sql.SQL('REVOKE ALL ON SCHEMA bmw_pm FROM {}').format(sql.Identifier(role)))
            raw.execute(sql.SQL('REVOKE ALL ON ALL TABLES IN SCHEMA bmw_pm FROM {}').format(sql.Identifier(role)))
    raw.execute('GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA bmw_pm TO bmw_pm_writer')
    raw.execute('REVOKE ALL ON FUNCTION bmw_pm.reject_mutation() FROM PUBLIC')
    connection.commit()
